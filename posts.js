function grad(s){
  if(s.tint) return `linear-gradient(180deg,rgba(185,71,47,.15) 0%,rgba(46,50,48,.9) 100%)`;
  if(s.g){ const [c,stop]=s.g.split(" "); return `linear-gradient(180deg,rgba(${c}) ${stop},rgba(0,0,0,.85) 100%)`; }
  return`linear-gradient(180deg,rgba(0,0,0,.2) 0%,rgba(0,0,0,.85) 100%)`;
}
